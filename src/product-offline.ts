export type ProductOfflinePlan = {
  command: string
  args: string[]
  mainRepo: string
  environmentOverrides: { LLM_LIVE_TESTS: '0' }
  removedEnvironmentNames: string[]
  suites: readonly ProductOfflineSuite[]
}

const strippedEnvironmentPattern =
  /(?:_API_KEY$|^AWS_(?:ACCESS_KEY_ID|SECRET_ACCESS_KEY|SESSION_TOKEN|PROFILE|DEFAULT_PROFILE)$|^GOOGLE_APPLICATION_CREDENTIALS$|^GOOGLE_CLOUD_PROJECT$|^VERTEX_AI_(?:PROJECT|LOCATION)$)/i

export function buildProductOfflinePlan(
  mainRepo = path.resolve(process.cwd(), '../paperlyft-html-review'),
): ProductOfflinePlan {
  return {
    command: process.execPath,
    args: [
      '--import',
      'tsx',
      'tools/run-local-check.ts',
      'vitest',
      'run',
      '--project=node',
      '--maxWorkers=1',
      ...PRODUCT_OFFLINE_SUITES.map((suite) => suite.path),
    ],
    mainRepo: path.resolve(mainRepo),
    environmentOverrides: { LLM_LIVE_TESTS: '0' },
    removedEnvironmentNames: [],
    suites: PRODUCT_OFFLINE_SUITES,
  }
}

export type ProductOfflineReport = {
  schemaVersion: 1
  category: 'offline-component-integration'
  startedAt: string
  finishedAt: string
  result: 'passed' | 'failed'
  exitCode: number | null
  command: string
  args: string[]
  workingDirectory: string
  environmentOverrides: { LLM_LIVE_TESTS: '0' }
  removedEnvironmentNames: string[]
  suites: readonly ProductOfflineSuite[]
  stdoutTail: string
  stderrTail: string
  error?: string
  boundary: string
}

export type RunProductOfflineOptions = {
  mainRepo?: string
  reportPath: string
  env?: NodeJS.ProcessEnv
  spawnImpl?: typeof spawn
}

export async function runProductOffline(
  options: RunProductOfflineOptions,
): Promise<ProductOfflineReport> {
  const plan = buildProductOfflinePlan(options.mainRepo)
  const environment: NodeJS.ProcessEnv = { ...(options.env ?? process.env) }
  const removedEnvironmentNames = Object.keys(environment).filter((key) =>
    strippedEnvironmentPattern.test(key),
  )
  for (const key of removedEnvironmentNames) delete environment[key]
  environment.LLM_LIVE_TESTS = '0'
  const startedAt = new Date().toISOString()
  const stdout = new BoundedTail(24_000)
  const stderr = new BoundedTail(24_000)
  let exitCode: number | null = null
  let errorMessage: string | undefined
  try {
    exitCode = await runChild(
      (options.spawnImpl ?? spawn)(plan.command, plan.args, {
        cwd: plan.mainRepo,
        env: environment,
        stdio: 'pipe',
        windowsHide: true,
      }),
      stdout,
      stderr,
    )
  } catch (error) {
    errorMessage = error instanceof Error ? error.message : String(error)
  }
  const report: ProductOfflineReport = {
    schemaVersion: 1,
    category: 'offline-component-integration',
    startedAt,
    finishedAt: new Date().toISOString(),
    result: exitCode === 0 && !errorMessage ? 'passed' : 'failed',
    exitCode,
    command: plan.command,
    args: plan.args,
    workingDirectory: plan.mainRepo,
    environmentOverrides: plan.environmentOverrides,
    removedEnvironmentNames: removedEnvironmentNames.sort(),
    suites: plan.suites,
    stdoutTail: stdout.toString(),
    stderrTail: stderr.toString(),
    ...(errorMessage ? { error: errorMessage } : {}),
    boundary:
      'These selected suites use test doubles and generated fixtures. Passing does not establish a full application processing run or real provider result.',
  }
  const absoluteReportPath = path.resolve(options.reportPath)
  await mkdir(path.dirname(absoluteReportPath), { recursive: true })
  await writeFile(absoluteReportPath, `${JSON.stringify(report, null, 2)}\n`, 'utf8')
  return report
}

class BoundedTail {
  private value = ''

  constructor(private readonly limit: number) {}

  append(chunk: Buffer | string): void {
    this.value = (this.value + chunk.toString()).slice(-this.limit)
  }

  toString(): string {
    return this.value
  }
}

function runChild(
  child: ChildProcessWithoutNullStreams,
  stdout: BoundedTail,
  stderr: BoundedTail,
): Promise<number | null> {
  return new Promise((resolve, reject) => {
    let settled = false
    child.stdout.on('data', (chunk: Buffer | string) => stdout.append(chunk))
    child.stderr.on('data', (chunk: Buffer | string) => stderr.append(chunk))
    child.once('error', (error) => {
      if (settled) return
      settled = true
      reject(error)
    })
    child.once('close', (code) => {
      if (settled) return
      settled = true
      resolve(code)
    })
  })
}
